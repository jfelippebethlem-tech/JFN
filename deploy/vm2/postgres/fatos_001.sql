-- fatos_001.sql — evolução das tabelas de FATOS do estágio E8 `fatos` (plano mestre v2 §3.2 E8, §6 "E8 destravado";
-- O6.3; ADR-001 linha D3: "fatos/leituras" no PG, escritor = E8).
--
-- As tabelas JÁ EXISTEM em produção (`jfn_evidencias`, esquema `public`, criadas por compliance_agent/leitura_integral.py:
-- 133.750 linhas em `fatos` medidas em 24/11/2026). Aqui elas só GANHAM colunas — nada é renomeado, nada é apagado, e as
-- linhas antigas (li-1/li-2) ficam como estão (colunas novas NULL = "fato do piloto, sem âncora de offset").
--
-- IDEMPOTENTE (IF NOT EXISTS). O nome do schema vem da variável `esquema` — produção é `public`; os testes aplicam o MESMO
-- arquivo num esquema temporário e o apagam no fim.
--   psql:   psql "$JFN_EVIDENCIAS_DSN" -v esquema=public -f deploy/vm2/postgres/fatos_001.sql
--   Python: python -m compliance_agent.aplicacao.estagios.fatos schema aplicar
--
-- Dado pessoal: a citação é texto dos autos (pode conter nome/CPF de quem assina, como as linhas antigas); o que sai da VM
-- para o modelo vai MASCARADO (dominio/mascara, estrito) — o mapa da máscara nunca é gravado aqui.

BEGIN;
SELECT pg_advisory_xact_lock(474748);   -- 474747 = evidencias._DDL_PG, 474749 = dominio_001.sql

CREATE SCHEMA IF NOT EXISTS :"esquema";
SET LOCAL search_path TO :"esquema";

-- as quatro tabelas como o leitura_integral as cria (só para o esquema temporário dos testes; em produção já existem)
CREATE TABLE IF NOT EXISTS leituras(processo TEXT NOT NULL, estagio TEXT NOT NULL, versao TEXT NOT NULL,
  chars_existentes INTEGER, chars_enviados INTEGER, fracao DOUBLE PRECISION, leitura TEXT, fatias INTEGER, lote TEXT,
  em TEXT NOT NULL, PRIMARY KEY(processo, estagio, versao));
CREATE TABLE IF NOT EXISTS fatos(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, processo TEXT NOT NULL,
  doc_id TEXT NOT NULL, tipo TEXT, valor TEXT, descricao TEXT, citacao TEXT, estado TEXT NOT NULL, motivo TEXT,
  motor TEXT, versao TEXT, payload_sha TEXT, em TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS ix_fatos_proc ON fatos(processo, estado);
CREATE INDEX IF NOT EXISTS ix_fatos_sha ON fatos(payload_sha);
CREATE TABLE IF NOT EXISTS tabelas_lidas(sha TEXT PRIMARY KEY, processo TEXT, doc_id TEXT, linhas INTEGER,
  linhas_com_numero INTEGER, em TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS docs_lidos(sha TEXT NOT NULL, versao TEXT NOT NULL, processo TEXT, doc_id TEXT, lote TEXT,
  em TEXT NOT NULL, PRIMARY KEY(sha, versao));

-- E8: âncora conferida de cada fato (documento + versão sha256 + página + offset) e a chave de idempotência da fatia
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS doc_sha TEXT;          -- sha256 do texto do documento citado (a versão)
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS pagina INTEGER;        -- 1 + nº de quebras de página (\f) antes do início
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS inicio INTEGER;        -- offset (caracteres) no texto do documento
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS fim INTEGER;           -- texto[inicio:fim] == citacao (substring exata)
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS contexto TEXT;         -- ±40 caracteres, só na citação curta com número
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS chave TEXT;            -- sha256(processo|sha da fatia|prompt_version|modelo)
ALTER TABLE fatos ADD COLUMN IF NOT EXISTS estagio_versao TEXT;   -- versão da lógica do E8 (fatos.VERSAO)
CREATE INDEX IF NOT EXISTS ix_fatos_chave ON fatos(chave);

-- E8: cobertura e chave do processo
ALTER TABLE leituras ADD COLUMN IF NOT EXISTS texto_sha TEXT;     -- sha256 do texto elegível do processo (doc_id:sha)
ALTER TABLE leituras ADD COLUMN IF NOT EXISTS modelo TEXT;
ALTER TABLE leituras ADD COLUMN IF NOT EXISTS chave TEXT;         -- sha256(processo|texto_sha|prompt_version|modelo)
ALTER TABLE leituras ADD COLUMN IF NOT EXISTS pecas_nao_lidas JSONB;   -- [{doc_id, motivo}] — o que NÃO foi lido e por quê
ALTER TABLE leituras ADD COLUMN IF NOT EXISTS fatos_verificados INTEGER;
ALTER TABLE leituras ADD COLUMN IF NOT EXISTS fatos_falha INTEGER;

COMMIT;
