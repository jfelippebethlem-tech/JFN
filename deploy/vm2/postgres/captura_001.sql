-- captura_001.sql — E2 `arvore` e E3 `capturar` (plano mestre v2 §3.2 E2/E3, item O3.3).
--
-- IDEMPOTENTE (IF NOT EXISTS / ON CONFLICT). Pré-requisito: as tabelas de compliance_agent/evidencias.py e a migração
-- evidencias_001.sql (aquisicao, versoes.hash_de/aquisicao_id) no esquema. Só ACRESCENTA: nada renomeado, nada apagado.
-- O nome do schema vem da variável `esquema` (produção `public`; os testes aplicam o MESMO arquivo num esquema
-- temporário e o apagam no fim).
--   Python: compliance_agent/aplicacao/estagios/arvore.py `schema aplicar` (troca :"esquema" com fluxo.schema.renderizar)
--
-- arvore_leitura  UMA linha por leitura da árvore viva (série temporal, nunca sobrescrita): tree_hash (sha256 da lista
--                 ORDENADA dos ids sem o sufixo #k — evidencias.hash_arvore), os ids e os documentos lidos (título,
--                 id_documento, restrito), por qual via, em que nó, e os processos relacionados. A leitura vigente de
--                 um processo é a de maior id. Idempotente pela posse do job (chave, ficha).
-- documentos      ganha `id_documento` (o do SEI, da url do nó; prova a identidade do `pos:<i>`) e `restrito`.

BEGIN;
SELECT pg_advisory_xact_lock(474751);        -- dois aplicadores ao mesmo tempo não disputam o DDL

SET LOCAL search_path TO :"esquema";

CREATE TABLE IF NOT EXISTS migracoes(versao text PRIMARY KEY, aplicada_em timestamptz NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS arvore_leitura(
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  processo      text        NOT NULL,
  tree_hash     text        NOT NULL,
  n_docs        integer     NOT NULL,
  ids           jsonb       NOT NULL,                  -- doc_id na ordem da árvore (com #k)
  docs          jsonb       NOT NULL,                  -- [{doc_id, i, titulo, id_documento, restrito}]
  relacionados  jsonb       NOT NULL DEFAULT '[]',
  via           text,                                  -- cracked | fallback/arvore_do_fonte | teste
  paginas       integer     NOT NULL DEFAULT 1,
  no            text,
  lente         jsonb       NOT NULL DEFAULT '[]',
  job_chave     text        NOT NULL,
  ficha         bigint      NOT NULL,
  lida_em       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT arvore_leitura_posse UNIQUE (job_chave, ficha)
);
CREATE INDEX IF NOT EXISTS arvore_leitura_processo_ix ON arvore_leitura (processo, id DESC);

ALTER TABLE documentos ADD COLUMN IF NOT EXISTS id_documento text;
ALTER TABLE documentos ADD COLUMN IF NOT EXISTS restrito boolean;
CREATE INDEX IF NOT EXISTS aquisicao_e3_ix ON aquisicao ((detalhe->>'processo')) WHERE fonte = 'sei:e3';

INSERT INTO migracoes(versao) VALUES ('captura_001') ON CONFLICT DO NOTHING;
COMMIT;
