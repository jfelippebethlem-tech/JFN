-- fluxo_001.sql — schema do motor de fluxo `jfn-fluxo` (plano mestre v2 §3.3, item O1.7; ADR-012).
--
-- IDEMPOTENTE: rodar de novo não muda nada (IF NOT EXISTS / CREATE OR REPLACE / ON CONFLICT).
-- O nome do schema vem da variável `esquema` — produção é `fluxo`; os testes aplicam o MESMO arquivo num esquema
-- temporário e o apagam no fim (lição de 23/11/2026: a suíte antiga esvaziava a tabela real).
--   psql:   psql "$JFN_EVIDENCIAS_DSN" -v esquema=fluxo -f deploy/vm2/postgres/fluxo_001.sql
--   Python: python -m compliance_agent.fluxo.schema aplicar        (o mesmo arquivo; troca :"esquema")
-- Dentro de corpo de função ($$…$$) não há :"esquema": as funções usam `SET search_path FROM CURRENT`, que
-- captura o search_path desta transação.
--
-- `fluxo.jobs` é tabela NOVA (ADR-012): a `public.jobs` de compliance_agent/evidencias.py segue servindo a leitura
-- integral até a migração na O3. Os nomes que já existiam lá (estado, prazo, ficha, chave, tentativas, dono,
-- criado_em, concluido_em) foram mantidos com o mesmo sentido.

BEGIN;
SELECT pg_advisory_xact_lock(474748);        -- dois aplicadores ao mesmo tempo não disputam o DDL

CREATE SCHEMA IF NOT EXISTS :"esquema";
SET LOCAL search_path TO :"esquema";

CREATE TABLE IF NOT EXISTS migracoes(versao text PRIMARY KEY, aplicada_em timestamptz NOT NULL DEFAULT now());

-- Ficha de posse = valor de uma sequência GLOBAL: identifica a reserva sozinha e só cresce. Quem tem a ficha
-- velha (lease vencido, job reservado por outro) é recusado ao concluir, falhar ou renovar (fencing).
CREATE SEQUENCE IF NOT EXISTS fichas;

CREATE TABLE IF NOT EXISTS jobs(
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo            text        NOT NULL,                   -- estágio: 'eco', 'coletar:pncp', 'ocr', …
  chave           text        NOT NULL,                   -- identidade do trabalho (idempotência); inclui o tipo
  estado          text        NOT NULL DEFAULT 'fila',
  prioridade      integer     NOT NULL DEFAULT 100,       -- menor = antes (como no propagacao.yaml)
  recursos        text[]      NOT NULL DEFAULT '{cpu_leve}',
  dono            text,                                   -- nó que reservou
  prazo           timestamptz,                            -- fim do lease (relógio do servidor)
  ficha           bigint      NOT NULL DEFAULT 0,
  heartbeat_em    timestamptz,
  tentativas      integer     NOT NULL DEFAULT 0,
  max_tentativas  integer     NOT NULL DEFAULT 5,
  disponivel_em   timestamptz NOT NULL DEFAULT now(),     -- backoff e debounce: antes disto ninguém reserva
  erro_tipo       text,
  erro_resumo     text,
  correlation_id  text,
  no_preferido    text,
  volta           jsonb,                                  -- para onde vai sem o nó preferido (§3.5)
  payload         jsonb       NOT NULL DEFAULT '{}',
  efeito          jsonb,                                  -- o que o estágio declarou e o supervisor conferiu
  criado_em       timestamptz NOT NULL DEFAULT now(),
  iniciado_em     timestamptz,
  concluido_em    timestamptz,
  CONSTRAINT jobs_chave_unica UNIQUE (chave),
  CONSTRAINT jobs_estado_valido CHECK (estado IN ('fila', 'reservado', 'feito', 'falhou_efeito', 'quarentena',
                                                  'cancelado'))
);
-- a reserva só olha a fila: índice parcial pequeno, na ordem do ORDER BY de fila.reservar
CREATE INDEX IF NOT EXISTS jobs_fila_ix ON jobs (prioridade, disponivel_em, id) WHERE estado = 'fila';
CREATE INDEX IF NOT EXISTS jobs_reservado_ix ON jobs (prazo) WHERE estado = 'reservado';
CREATE INDEX IF NOT EXISTS jobs_ficha_ix ON jobs (ficha);
-- fila quente: muitas atualizações por linha. Autovacuum agressivo para o índice parcial não inchar.
ALTER TABLE jobs SET (autovacuum_vacuum_scale_factor = 0.01, autovacuum_vacuum_threshold = 50,
                      autovacuum_analyze_scale_factor = 0.02, autovacuum_vacuum_cost_delay = 0,
                      fillfactor = 80);

-- arquivamento mensal: job FEITO há mais de N dias sai da tabela quente. Quarentena e falhou_efeito ficam (são
-- trabalho pendente de gente). Depois de arquivada, a mesma chave pode ser enfileirada de novo.
CREATE TABLE IF NOT EXISTS jobs_arquivo (LIKE jobs INCLUDING DEFAULTS);
CREATE OR REPLACE FUNCTION arquivar_jobs(dias integer DEFAULT 30) RETURNS bigint
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE n bigint;
BEGIN
  WITH m AS (DELETE FROM jobs WHERE estado = 'feito' AND concluido_em < now() - make_interval(days => dias)
             RETURNING *)
  INSERT INTO jobs_arquivo SELECT * FROM m;
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;

-- job novo na fila acorda os supervisores (LISTEN jfn_jobs); eles também acordam sozinhos a cada 60 s
CREATE OR REPLACE FUNCTION notificar_job() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
  PERFORM pg_notify('jfn_jobs', NEW.tipo);
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER jobs_notificar AFTER INSERT ON jobs
  FOR EACH ROW WHEN (NEW.estado = 'fila') EXECUTE FUNCTION notificar_job();

-- outbox durável: o job concluído grava aqui na MESMA transação; o planejador transforma em jobs dependentes.
-- Substitui o propagacao.db e a sonda MAX(rowid), que não via UPDATE.
CREATE TABLE IF NOT EXISTS eventos(
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte         text        NOT NULL,
  chave         text,
  tipo          text        NOT NULL,
  detalhe       jsonb       NOT NULL DEFAULT '{}',
  quando        timestamptz NOT NULL DEFAULT now(),
  processado_em timestamptz
);
CREATE INDEX IF NOT EXISTS eventos_pendentes_ix ON eventos (id) WHERE processado_em IS NULL;

-- o ÚNICO lugar onde mora horário (substitui crontab, timers e o `schedule` do yaml)
CREATE TABLE IF NOT EXISTS agenda(
  id        text        PRIMARY KEY,
  cron_expr text        NOT NULL,                         -- 5 campos, hora de Brasília
  proximo   timestamptz,                                  -- NULL = recém-criada: só calcula, não dispara
  tipo_job  text        NOT NULL,
  payload   jsonb       NOT NULL DEFAULT '{}',
  ativo     boolean     NOT NULL DEFAULT true,
  dono      text
);

CREATE TABLE IF NOT EXISTS nos(
  no            text PRIMARY KEY,
  capacidades   jsonb       NOT NULL DEFAULT '{}',
  slots         jsonb       NOT NULL DEFAULT '{}',
  psi           jsonb       NOT NULL DEFAULT '{}',
  versao_codigo text,
  heartbeat_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS metricas(
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no      text,
  nome    text             NOT NULL,
  valor   double precision NOT NULL,
  quando  timestamptz      NOT NULL DEFAULT now(),
  rotulos jsonb            NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS metricas_nome_quando_ix ON metricas (nome, quando);

INSERT INTO migracoes(versao) VALUES ('fluxo_001') ON CONFLICT DO NOTHING;
COMMIT;
