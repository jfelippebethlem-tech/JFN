-- evidencias_001.sql — proveniência da identidade: `aquisicao` e `transformacao` (plano mestre v2 §3.8, item O3.2).
--
-- IDEMPOTENTE: rodar de novo não muda nada (IF NOT EXISTS / ON CONFLICT).
-- Pré-requisito: as tabelas de compliance_agent/evidencias.py (processos, arvores, documentos, versoes) já existem no
-- esquema — `evidencias.conectar()` as cria; `tools/evidencias_carga_manifestos.py` chama os dois nessa ordem.
-- O nome do schema vem da variável `esquema` — produção é `public` (onde evidencias.py grava); os testes aplicam o
-- MESMO arquivo num esquema temporário e o apagam no fim.
--   psql:   psql "$JFN_EVIDENCIAS_DSN" -v esquema=public -f deploy/vm2/postgres/evidencias_001.sql
--   Python: tools/evidencias_carga_manifestos.py (troca :"esquema" com compliance_agent.fluxo.schema.renderizar)
--
-- aquisicao     DE ONDE veio um conteúdo: uma rodada de coleta/captura (fonte, nó, ferramenta, versão do código,
--               início/fim). A linha 'legado' representa tudo o que já estava no data/sei_arquivo antes da esteira —
--               a captura original não registrou proveniência, e isso fica dito em vez de inventado.
-- transformacao O QUE se fez com um conteúdo para obter outro (extração de texto, OCR, …): entrada → saída por sha256,
--               com motor e versão. O legado não ganha linha aqui: a entrada (o binário) não foi guardada.
-- versoes       ganha `hash_de` ('texto' = sha256 do texto sem etiqueta; 'binario' = do PDF/HTML original) e
--               `aquisicao_id`.

BEGIN;
SELECT pg_advisory_xact_lock(474749);        -- dois aplicadores ao mesmo tempo não disputam o DDL

SET LOCAL search_path TO :"esquema";

CREATE TABLE IF NOT EXISTS migracoes(versao text PRIMARY KEY, aplicada_em timestamptz NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS aquisicao(
  id             text        PRIMARY KEY,
  fonte          text        NOT NULL,                  -- 'sei_arquivo', 'sei:integra', 'siafe', …
  no             text,                                  -- máquina que adquiriu (vm1, vm2, itcampo)
  ferramenta     text,                                  -- estágio/script que adquiriu
  versao_codigo  text,                                  -- commit do código que adquiriu
  iniciada_em    timestamptz,
  concluida_em   timestamptz,
  detalhe        jsonb       NOT NULL DEFAULT '{}',
  criada_em      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS transformacao(
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  processo       text        NOT NULL,
  doc_id         text        NOT NULL,
  tipo           text        NOT NULL,                  -- 'texto_nativo', 'ocr', 'ocr_gpu', …
  entrada_sha    text,                                  -- versão de origem (NULL = a entrada não foi guardada)
  saida_sha      text        NOT NULL,                  -- versão produzida
  motor          text,
  versao_motor   text,
  parametros     jsonb       NOT NULL DEFAULT '{}',
  aquisicao_id   text        REFERENCES aquisicao(id),
  criada_em      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT transformacao_unica UNIQUE NULLS NOT DISTINCT (processo, doc_id, tipo, entrada_sha, saida_sha, motor,
                                                            versao_motor)
);
CREATE INDEX IF NOT EXISTS transformacao_saida_ix ON transformacao (saida_sha);

ALTER TABLE versoes ADD COLUMN IF NOT EXISTS hash_de text;
ALTER TABLE versoes ADD COLUMN IF NOT EXISTS aquisicao_id text;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'versoes_aquisicao_fk'
                 AND conrelid = 'versoes'::regclass) THEN
    ALTER TABLE versoes ADD CONSTRAINT versoes_aquisicao_fk FOREIGN KEY (aquisicao_id) REFERENCES aquisicao(id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'versoes_hash_de_valido'
                 AND conrelid = 'versoes'::regclass) THEN
    ALTER TABLE versoes ADD CONSTRAINT versoes_hash_de_valido CHECK (hash_de IN ('texto', 'binario'));
  END IF;
END $$;

INSERT INTO aquisicao(id, fonte, ferramenta, detalhe)
VALUES ('legado', 'sei_arquivo', 'tools/evidencias_carga_manifestos.py',
        '{"descricao": "acervo data/sei_arquivo anterior à esteira (O3.1): captura original sem registro de proveniência"}')
ON CONFLICT (id) DO NOTHING;

INSERT INTO migracoes(versao) VALUES ('evidencias_001') ON CONFLICT DO NOTHING;
COMMIT;
